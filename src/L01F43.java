package faccat;

public class L01F43 {
    public static void main(String[] args) {
        int numero = 8;
        System.out.println("--- Tabuada do 8 ---");
        for (int i = 1; i <= 10; i++) {
            int resultado = numero * i;
            System.out.println(numero + " x " + i + " = " + resultado);
        }
    }
}